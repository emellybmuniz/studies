# Assignment Operators in Python

# Simple assignment
x = 10  # x is assigned the value 10

# Add and assign
x += 5  # equivalent to x = x + 5, now x is 15

# Subtract and assign
x -= 3  # equivalent to x = x - 3, now x is 12

# Multiply and assign
x *= 2  # equivalent to x = x * 2, now x is 24

# Divide and assign
x /= 4  # equivalent to x = x / 4, now x is 6.0

# Floor division and assign
x //= 2  # equivalent to x = x // 2, now x is 3.0

# Modulus and assign
x %= 2  # equivalent to x = x % 2, now x is 1.0

# Exponentiation and assign
x **= 3  # equivalent to x = x ** 3, now x is 1.0
